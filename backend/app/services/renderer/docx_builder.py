"""Orchestrate full DOCX build from theme + blocks + meta."""

from __future__ import annotations

from pathlib import Path

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.shared import Pt, RGBColor

from app import APP_NAME
from app.config import get_settings
from app.models.blocks import Block
from app.models.document import DocumentMeta, RenderOptions
from app.models.theme import Theme
from app.services.renderer.blocks import render_blocks
from app.services.renderer.cover import add_cover
from app.services.renderer.header_footer import setup_header_footer
from app.services.renderer.layout import plan_layout
from app.services.renderer.oxml import add_toc_field, set_page_border
from app.services.renderer.revision import add_revision_history
from app.services.renderer.styles import apply_theme_styles


def build_docx(
    *,
    source_text: str,
    blocks: list[Block],
    theme: Theme,
    meta: DocumentMeta,
    options: RenderOptions | None = None,
    out_path: Path | str,
    logo_bytes: bytes | None = None,
    logo_path: str | Path | None = None,
) -> Path:
    options = options or RenderOptions()
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    doc = Document()
    apply_theme_styles(doc, theme)

    # Core properties
    core = doc.core_properties
    core.title = meta.title
    core.author = meta.author or APP_NAME
    core.subject = meta.subject or meta.classification
    core.comments = f"Generated by {APP_NAME}"

    # Document language
    _set_document_language(doc, "en-US")

    section = doc.sections[0]
    if options.border:
        set_page_border(
            section,
            theme.border.color,
            width_pt=theme.border.width_pt,
            offset_pt=theme.border.offset_pt,
        )

    setup_header_footer(doc, theme, meta, options)

    plan = plan_layout(
        blocks=blocks,
        source=source_text,
        meta=meta,
        options=options,
        layout=theme.layout,
    )

    if plan.include_cover:
        add_cover(doc, theme, meta, options, logo_bytes=logo_bytes, logo_path=logo_path)

    if plan.include_revision_page:
        add_revision_history(doc, theme, meta, page_break=not plan.include_toc)
    elif plan.compact_revision_on_cover:
        # Compact RH already belongs on cover in PDF; DOCX appends after cover break
        # Undo last page break by adding RH before body without extra control page
        add_revision_history(doc, theme, meta, page_break=False)

    if plan.include_toc:
        toc_heading = doc.add_heading("Table of Contents", level=1)
        toc_para = doc.add_paragraph()
        add_toc_field(toc_para)
        doc.add_page_break()
        _ = toc_heading

    render_blocks(doc, blocks, source_text, theme)

    settings = get_settings()
    if options.watermark or settings.watermark_free_tier:
        _add_watermark_paragraph(doc, f"Made with {APP_NAME}")

    doc.save(str(out_path))
    return out_path


def _set_document_language(doc: Document, lang: str) -> None:
    styles = doc.styles
    style = styles["Normal"]
    rpr = style.element.get_or_add_rPr()
    lang_el = rpr.find(qn("w:lang"))
    if lang_el is None:
        from docx.oxml import OxmlElement

        lang_el = OxmlElement("w:lang")
        rpr.append(lang_el)
    lang_el.set(qn("w:val"), lang)
    lang_el.set(qn("w:eastAsia"), lang)
    lang_el.set(qn("w:bidi"), lang)


def _add_watermark_paragraph(doc: Document, text: str) -> None:
    # Lightweight free-tier footer note (true diagonal watermark is Word VML; keep simple).
    para = doc.add_paragraph()
    para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = para.add_run(text)
    run.font.size = Pt(8)
    run.font.italic = True
    run.font.color.rgb = RGBColor(0x99, 0x99, 0x99)
